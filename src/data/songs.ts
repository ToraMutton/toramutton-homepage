// 年は「その曲が最初に世に出た年」(先行シングルはシングルの年)。
// インストゥルメンタルと、別アルバムとの重複曲は入れていない。

export interface Song {
  title: string;
  artist: string;
  year: string;
}

type Track = [title: string, year: string];

const byArtist = (artist: string, tracks: Track[]): Song[] =>
  tracks.map(([title, year]) => ({ title, artist, year }));

